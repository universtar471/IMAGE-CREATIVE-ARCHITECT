/**
 * Canonical JSON and a synchronous SHA-256 for prompt provenance hashes (ADR-034).
 *
 * Pure TypeScript with no dependency, so the compiler stays synchronous and identical in the
 * desktop app, tests and scripts. Not used for security.
 */

/**
 * JSON with object keys sorted by UTF-16 code unit at every level and no whitespace.
 * `undefined` object members are dropped and `undefined` array items become `null`, as in
 * `JSON.stringify`; non-finite numbers become `null` and -0 becomes 0.
 */
export function canonicalJson(value: unknown): string {
  return write(value) ?? "null";
}

function write(value: unknown): string | undefined {
  if (value === null) return "null";
  switch (typeof value) {
    case "string":
      return JSON.stringify(value);
    case "number":
      return Number.isFinite(value) ? JSON.stringify(value === 0 ? 0 : value) : "null";
    case "boolean":
      return value ? "true" : "false";
    case "bigint":
      return value.toString();
    case "undefined":
    case "function":
    case "symbol":
      return undefined;
  }
  if (Array.isArray(value)) return `[${value.map((item) => write(item) ?? "null").join(",")}]`;
  const record = value as Record<string, unknown>;
  const toJson = (record as { toJSON?: () => unknown }).toJSON;
  if (typeof toJson === "function") return write(toJson.call(record));
  const members: string[] = [];
  for (const key of Object.keys(record).sort()) {
    const text = write(record[key]);
    if (text !== undefined) members.push(`${JSON.stringify(key)}:${text}`);
  }
  return `{${members.join(",")}}`;
}

